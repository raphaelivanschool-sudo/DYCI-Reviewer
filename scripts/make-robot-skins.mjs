/**
 * Makes the robot skins (level rewards) from the original robot layers in assets/robot.
 *
 *   node scripts/make-robot-skins.mjs
 *
 * Each skin is the same 3D render recolored with CSS filters, drawn in a headless Edge/Chrome canvas.
 * Output:
 *   assets/robot/skins/<id>/robot-*.webp   one folder per skin
 *   src/components/robot-skins.ts          require() map used by <Robot skin="..."> (generated, don't edit)
 *
 * To add a skin: add it to SKINS below, run this script, then give it a level in LEVEL_REWARDS (src/lib/game.ts).
 * Set BROWSER=/path/to/chrome if Edge is not at the default Windows path.
 */
import { spawn } from 'node:child_process';
import { createServer } from 'node:http';
import { mkdirSync, readFileSync, writeFileSync, rmSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(ROOT, 'assets', 'robot');
const OUT = join(SRC, 'skins');
const BROWSER = process.env.BROWSER || 'C:\\Program Files (x86)\\Microsoft\\Edge\\Application\\msedge.exe';

const LAYERS = ['robot-body', 'robot-head', 'robot-fin', 'robot-wingL', 'robot-wingR', 'robot-upperL', 'robot-upperR', 'robot-lowerL', 'robot-lowerR'];

/** id → CSS filter. sepia() first gives the white body a warm base color that hue-rotate then turns. */
const SKINS = {
  mint: 'sepia(.45) saturate(2.2) hue-rotate(105deg) brightness(1.02)',
  ocean: 'sepia(.45) saturate(2.6) hue-rotate(160deg)',
  grape: 'sepia(.45) saturate(2.4) hue-rotate(225deg)',
  sunset: 'sepia(.55) saturate(3) hue-rotate(-20deg)',
  lime: 'sepia(.5) saturate(2.6) hue-rotate(45deg) brightness(1.03)',
  rose: 'sepia(.45) saturate(2.6) hue-rotate(295deg)',
  sky: 'sepia(.35) saturate(2.4) hue-rotate(170deg) brightness(1.08)',
  midnight: 'sepia(.6) saturate(2.4) hue-rotate(190deg) brightness(.62) contrast(1.15)',
  coral: 'sepia(.5) saturate(3) hue-rotate(-35deg) brightness(1.04)',
  gold: 'sepia(.95) saturate(3.4) hue-rotate(-8deg) brightness(1.02)',
  galaxy: 'sepia(.6) saturate(2.8) hue-rotate(235deg) brightness(.7) contrast(1.2)',
};

const layers = Object.fromEntries(LAYERS.map((n) => [n, `data:image/webp;base64,${readFileSync(join(SRC, `${n}.webp`)).toString('base64')}`]));

// The page recolors every layer in a canvas and POSTs the results back to this tiny local server.
const html = `<!doctype html><meta charset="utf-8"><body><script>
const L=${JSON.stringify(layers)}, S=${JSON.stringify(SKINS)};
const load=(src)=>new Promise((ok,no)=>{const i=new Image();i.onload=()=>ok(i);i.onerror=no;i.src=src;});
(async()=>{const res={};
  for(const [n,src] of Object.entries(L)){const img=await load(src);
    for(const [id,f] of Object.entries(S)){const c=document.createElement('canvas');c.width=img.naturalWidth;c.height=img.naturalHeight;
      const x=c.getContext('2d');x.filter=f;x.drawImage(img,0,0);(res[id]??={})[n]=c.toDataURL('image/webp',0.92);}}
  await fetch('/done',{method:'POST',body:JSON.stringify(res)});})();
</script>`;

const tmp = mkdtempSync(join(tmpdir(), 'skins-'));
let browser;
const res = await new Promise((resolve, reject) => {
  const server = createServer((req, reply) => {
    if (req.method === 'POST') {
      let body = '';
      req.on('data', (c) => (body += c));
      req.on('end', () => {
        reply.end('ok');
        server.close();
        resolve(JSON.parse(body));
      });
      return;
    }
    reply.setHeader('Content-Type', 'text/html');
    reply.end(html);
  });
  server.listen(0, '127.0.0.1', () => {
    const { port } = server.address();
    browser = spawn(BROWSER, ['--headless=new', '--disable-gpu', `--user-data-dir=${join(tmp, 'profile')}`, `http://127.0.0.1:${port}/`], { stdio: 'ignore' });
    browser.on('error', reject);
  });
  setTimeout(() => reject(new Error(`No images after 60 s. Is the browser path right? (${BROWSER})`)), 60_000).unref();
});
browser?.kill();
try {
  rmSync(tmp, { recursive: true, force: true, maxRetries: 5, retryDelay: 300 });
} catch {
  // The browser may still hold its profile folder for a moment; it's only a temp folder.
}

rmSync(OUT, { recursive: true, force: true });
for (const [id, files] of Object.entries(res)) {
  mkdirSync(join(OUT, id), { recursive: true });
  for (const [n, url] of Object.entries(files)) writeFileSync(join(OUT, id, `${n}.webp`), Buffer.from(url.split(',')[1], 'base64'));
}

const part = { wingLeft: 'robot-wingR', wingRight: 'robot-wingL', upperLeft: 'robot-upperR', lowerLeft: 'robot-lowerR', upperRight: 'robot-upperL', lowerRight: 'robot-lowerL', body: 'robot-body', fin: 'robot-fin', head: 'robot-head' };
const ts = `// Generated by scripts/make-robot-skins.mjs. Do not edit by hand.
export type RobotSkinId = 'classic' | ${Object.keys(SKINS).map((k) => `'${k}'`).join(' | ')};
type Layers = Record<'${Object.keys(part).join("' | '")}', number>;

export const SKIN_LAYERS: Record<Exclude<RobotSkinId, 'classic'>, Layers> = {
${Object.keys(SKINS).map((id) => `  ${id}: {\n${Object.entries(part).map(([k, f]) => `    ${k}: require('../../assets/robot/skins/${id}/${f}.webp'),`).join('\n')}\n  },`).join('\n')}
};
`;
writeFileSync(join(ROOT, 'src', 'components', 'robot-skins.ts'), ts);
console.log(`Made ${Object.keys(res).length} skins in assets/robot/skins and src/components/robot-skins.ts`);
